// 1. Operator Aritmatika
let a = 10;
let b = 2;
// Penjumlahan
console.log(a + b);
// Pengurang
console.log(a - b);
// Perkalian
console.log(a * b);
// Pembagian
console.log(a / b);
// Perpangkatan
console.log(a ** b);

// 2. Concatenation -> cara menggabungkan string
console.log("Hello" + " " + "Dunia");

// 3. Operator Koma
console.log("Hello", "Dunia");

// 4. Template Literal `${}`
console.log(`a = ${a} + b = ${b} hasil nya adalah ${a + b}`);

// 5. Operator Penugasan/Assignment (=)

// Penugasan
let angka1 = 20;
console.log(angka1);

// Penugasan dan Penjumlahan
angka1 += 10;
console.log(angka1);

// Penugasan dan Pengurangan
angka1 -= 2;
console.log(angka1);
// Penugasan dan Perkalian
angka1 *= 3 / 4;
console.log(angka1);
// Penugasan dan Pembagian
angka1 /= 2;
console.log(angka1);
// Penugasan dan Perpangkatan
angka1 **= 2;
console.log(angka1);

// 6. Increment dan Decrement (+1, -1)
let i = 2;
// -. Postfix Increment
console.log(i++);
console.log(i);
// -. Prefix Increment
console.log(++i);

// -. Postfix Decrement
console.log(i--);
console.log(i);
// -. Prefix Decrement
console.log(--i);
