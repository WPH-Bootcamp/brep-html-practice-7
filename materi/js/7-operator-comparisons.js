// Operator Comparison (Perbandingan)
let umurUcup = 25;
let umurRenday = 20;

// 1. Sama dengan (==/===)
console.log(umurUcup == umurRenday);
console.log(umurUcup === umurRenday);

// 2. Tidak Sama dengan (!=/!==)
console.log(umurUcup != umurRenday);
console.log(umurUcup !== umurRenday);

// 3. Lebih besar (>)
console.log(umurUcup > umurRenday);

// 4. Lebih besar atau Sama dengna (>=)
console.log(umurUcup >= umurRenday);

// 5. Lebih kecil (<)
console.log(umurUcup < umurRenday);

// 6. Lebih kecil atau Sama dengan (<=)
console.log(umurUcup <= umurRenday);
